// The editor's code lives in renderer/src/*.js (one file per area, in load order).
// Browsers need one classic script (functions in one file call functions in another), so this joins them into renderer/app.js.
// Run:  npm run build:renderer     (npm start / npm run dist / npm test do it for you)
const fs = require('fs'), path = require('path');
const src = path.join(__dirname, '..', 'renderer', 'src'), out = path.join(__dirname, '..', 'renderer', 'app.js');
const HEAD = '// GENERATED by scripts/build-renderer.js from renderer/src/*.js. Do not edit this file, edit the files in src/ instead.\n';
function bundle() {
  const files = fs.readdirSync(src).filter(f => /\.js$/.test(f)).sort();
  return HEAD + files.map(f => '/* ===== src/' + f + ' ===== */\n' + fs.readFileSync(path.join(src, f), 'utf8').replace(/\s+$/, '') + '\n').join('\n');
}
if (require.main === module) {
  const b = bundle();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (cur !== b) { console.error('renderer/app.js is out of date. Run: npm run build:renderer'); process.exit(1); }
    console.log('renderer/app.js is up to date');
  } else { fs.writeFileSync(out, b); console.log('wrote renderer/app.js (' + Math.round(b.length / 1024) + ' KB from ' + fs.readdirSync(src).length + ' files)'); }
}
module.exports = { bundle };
